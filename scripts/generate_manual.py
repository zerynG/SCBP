"""
Генератор инструкции пользователя SCBP в формате .docx (со скриншотами).

Запуск:
    python scripts/generate_manual.py

Результат: docs/manual/SCBP-instrukciya.docx
Скриншоты берутся из docs/manual/img/ (снимаются отдельно из работающего приложения).
"""
import os

from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor, Cm

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG = os.path.join(BASE, 'docs', 'manual', 'img')
OUT = os.path.join(BASE, 'docs', 'manual', 'SCBP-instrukciya.docx')

ACCENT = RGBColor(0x6D, 0x4A, 0xC0)
MUTED = RGBColor(0x70, 0x70, 0x70)


def add_pic(doc, fname, width_cm=16.0):
    path = os.path.join(IMG, fname)
    if os.path.exists(path):
        doc.add_picture(path, width=Cm(width_cm))
        doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    else:
        p = doc.add_paragraph(f'[нет скриншота: {fname}]')
        p.runs[0].italic = True


def h(doc, text, level=1):
    doc.add_heading(text, level=level)


def caption(doc, text):
    p = doc.add_paragraph(text)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.runs[0]; r.italic = True; r.font.size = Pt(9); r.font.color.rgb = MUTED


def bullet(doc, text):
    doc.add_paragraph(text, style='List Bullet')


def build():
    doc = Document()
    # базовый шрифт
    st = doc.styles['Normal']
    st.font.name = 'Calibri'; st.font.size = Pt(11)

    # --- Титул ---
    t = doc.add_paragraph(); t.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = t.add_run('SCBP'); r.bold = True; r.font.size = Pt(40); r.font.color.rgb = ACCENT
    s = doc.add_paragraph('Система расчёта стоимости проекта'); s.alignment = WD_ALIGN_PARAGRAPH.CENTER
    s.runs[0].font.size = Pt(16)
    sub = doc.add_paragraph('Руководство пользователя'); sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sub.runs[0].font.size = Pt(13); sub.runs[0].font.color.rgb = MUTED
    doc.add_paragraph()

    # --- О системе ---
    h(doc, '1. О системе', 1)
    doc.add_paragraph(
        'SCBP — веб-приложение для расчёта себестоимости и отпускной цены проекта по '
        'привлекаемым ресурсам: штатные сотрудники, исполнители (ГПХ/НПД), подрядчики '
        '(юр./физ. лица) и оборудование/ПО. Система автоматически считает стоимость с '
        'учётом периода работ, производственного календаря РФ, страховых взносов, наценки '
        'и НДС, а также формирует документы (КП, НМА, смета) в PDF/Excel/Word.')

    # --- Главный экран ---
    h(doc, '2. Главный экран', 1)
    doc.add_paragraph('После входа открывается дашборд с разделами:')
    bullet(doc, 'Создание ресурсов (Каталог) — справочник сотрудников, исполнителей, подрядчиков, оборудования.')
    bullet(doc, 'Управление проектами — создание проектов, назначение ресурсов, расчёт.')
    bullet(doc, 'Генерация документов — КП, НМА, сметы в PDF/Excel/Word.')
    bullet(doc, 'Диаграмма Ганта — расписание сотрудников по проектам.')
    bullet(doc, 'Реестр услуг — справочник услуг для назначения ресурсам.')
    add_pic(doc, '01-dashboard.png')
    caption(doc, 'Рис. 1. Главный экран (дашборд)')

    # --- Каталог ---
    h(doc, '3. Каталог ресурсов', 1)
    doc.add_paragraph(
        'В «Каталоге» создаются ресурсы по вкладкам. Для оборудования выбирается тип '
        'тарификации: помесячная, посуточная, почасовая или поминутная — и вводится '
        'соответствующая ставка.')
    add_pic(doc, '06-catalog.png')
    caption(doc, 'Рис. 2. Каталог ресурсов')

    # --- Реестр услуг ---
    h(doc, '4. Реестр услуг', 1)
    doc.add_paragraph(
        'Услуги — глобальный справочник, который назначается ресурсам в проекте. У каждой '
        'услуги есть поле «Применяется к» (Любой ресурс / Сотрудники / Исполнители / '
        'Подрядчики / Оборудование). В строке ресурса в выпадающем списке показываются '
        'только подходящие по типу услуги. Услуги можно добавлять, редактировать, '
        'скрывать (флаг «Активна») и удалять; виден счётчик использования.')
    add_pic(doc, '04-services.png', 15.0)
    caption(doc, 'Рис. 3. Реестр услуг (сгруппирован по категориям «Применяется к»)')

    # --- Финансовые показатели ---
    h(doc, '5. Управление проектом: финансовые показатели', 1)
    doc.add_paragraph('В карточке «Финансовые показатели» задаются настраиваемые параметры расчёта:')
    bullet(doc, 'Страховые взносы на ФОТ (%) — начисляются ТОЛЬКО на оклад штатных сотрудников и входят в себестоимость. На исполнителей, подрядчиков и оборудование не начисляются.')
    bullet(doc, 'Наценка / рентабельность (%) — надбавка к себестоимости ресурса. У каждого ресурса можно задать свою наценку (пусто = наценка проекта, 0 = строгий ноль).')
    bullet(doc, 'НДС (%) — начисляется ОДИН раз на итоговую цену (output) и НЕ входит в прибыль. По умолчанию 0 (напр., УСН без НДС).')
    bullet(doc, 'Часов в дне (КЧЧ) — для отображения часов сотрудника и расчёта оборудования.')
    doc.add_paragraph('Все параметры по умолчанию 0 — ничего не начисляется, пока не задано. KPI-карточки: Себестоимость → Цена без НДС → НДС → Цена с НДС → Чистая прибыль.')
    add_pic(doc, '02-project-finance.png')
    caption(doc, 'Рис. 4. Параметры проекта и финансовые KPI')

    # --- Сводная таблица ---
    h(doc, '6. Сводная таблица ресурсов', 1)
    doc.add_paragraph(
        'Ресурсы сгруппированы по типам (Сотрудники / Исполнители / Подрядчики / '
        'Оборудование). У каждой группы — счётчик и подытог (сумма «Итого»). В строке '
        'настраиваются: услуга, наценка, период работ (начало/окончание) и количество '
        'часов (для исполнителей/почасовых подрядчиков). Все изменения сохраняются '
        'автоматически, а числа пересчитываются мгновенно. Внизу — «ИТОГО ПО ПРОЕКТУ».')
    add_pic(doc, '03-resource-table.png')
    caption(doc, 'Рис. 5. Сводная таблица (группировка по типам, подытоги)')

    doc.add_paragraph('Период оборудования берётся из дат в таблице; если не задано — от даты '
                      'приобретения до конца проекта. Тарификация всегда по календарным дням периода:')
    bullet(doc, 'Помесячно: число месяцев (округление вверх) × ставка.')
    bullet(doc, 'Посуточно: календарных дней × ставка.')
    bullet(doc, 'Почасово: дней × 24 ч × ставка.')
    bullet(doc, 'Поминутно: дней × 24 × 60 мин × ставка (цена показывается за минуту).')

    # --- Формулы ---
    h(doc, '7. Формулы расчёта', 1)
    doc.add_paragraph('На уровне строки ресурса:')
    p = doc.add_paragraph(); p.add_run(
        'cost (себестоимость) = база × (1 + взносы/100)   — взносы только для сотрудников\n'
        'final (итого)        = cost × (1 + наценка/100)'
    ).font.name = 'Consolas'
    doc.add_paragraph('На уровне проекта:')
    p = doc.add_paragraph(); p.add_run(
        'Себестоимость = Σ cost\n'
        'Цена без НДС  = Σ final\n'
        'Чистая прибыль = Цена без НДС − Себестоимость   (НДС в прибыль не входит)\n'
        'НДС           = Цена без НДС × НДС%/100\n'
        'Цена с НДС    = Цена без НДС + НДС'
    ).font.name = 'Consolas'

    doc.add_paragraph('«База» по типам ресурса:')
    bullet(doc, 'Сотрудник: оклад × (рабочие дни периода − недоступные) / рабочих дней в месяце (по производственному календарю). Без дат — полный оклад.')
    bullet(doc, 'Исполнитель: ставка/час × часы.')
    bullet(doc, 'Подрядчик: фиксированная сумма договора, либо ставка/час × часы.')
    bullet(doc, 'Оборудование: ставка × число единиц периода (мес/дн/час/мин) × количество.')

    # --- Проверочный пример ---
    h(doc, '8. Проверка корректности (пример)', 1)
    doc.add_paragraph('Демо-проект: взносы = 30%, НДС = 22%, наценка = 15%. Сверка отображаемых '
                      'значений с расчётом «вручную» (фрагмент):')
    rows = [
        ('Ресурс', 'База', 'Себест.', 'Итого', 'Проверка'),
        ('Петрова (сотрудник, без дат)', '150 000', '195 000', '224 250', '150000×1.30×1.15'),
        ('Кузнецов (исполнитель, 120 ч × 1500)', '180 000', '180 000', '207 000', 'без взносов ×1.15'),
        ('ООО Интегратор (подрядчик, фикс)', '500 000', '500 000', '575 000', '500000×1.15'),
        ('Тестовый стенд (оборуд., 150 дн × 1500 × 2)', '450 000', '450 000', '517 500', 'посуточно ×1.15'),
        ('Сервер Dell (оборуд., 4 мес × 25000)', '100 000', '100 000', '115 000', 'помесячно ×1.15'),
        ('GPU (оборуд., 4128 ч × 300)', '1 238 400', '1 238 400', '1 424 160', 'почасово ×1.15'),
    ]
    table = doc.add_table(rows=0, cols=5); table.style = 'Light Grid Accent 1'
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for ri, row in enumerate(rows):
        cells = table.add_row().cells
        for ci, val in enumerate(row):
            cells[ci].text = val
            for par in cells[ci].paragraphs:
                for run in par.runs:
                    run.font.size = Pt(9)
                    if ri == 0:
                        run.bold = True
    doc.add_paragraph('Итоги проекта: Цена без НДС = 7 040 939,26 ₽; НДС 22% = 1 549 006,64 ₽; '
                      'Цена с НДС = 8 589 945,90 ₽. Все значения сходятся с ручным расчётом, '
                      'а живой пересчёт при изменении наценки/дат/часов проверен.')

    # --- Документы ---
    h(doc, '9. Генерация документов', 1)
    doc.add_paragraph('На странице документов проекта формируются КП, НМА и смета в форматах '
                      'PDF, Excel и Word. В итоговую стоимость подставляются те же числа, что и '
                      'в сводной таблице; при НДС > 0 добавляется строка с разбивкой НДС.')
    add_pic(doc, '05-documents.png', 15.0)
    caption(doc, 'Рис. 6. Генерация документов')

    # --- Быстрый старт ---
    h(doc, '10. Быстрый старт и что смотреть', 1)
    doc.add_paragraph('База данных уже включена (демо-данные) — создавать пользователя не нужно.')
    bullet(doc, 'Запуск: python3 -m venv venv → активировать → pip install -r requirements.txt → python manage.py runserver')
    bullet(doc, 'Открыть http://127.0.0.1:8000/login/  ·  Email: admin@demo.local  ·  Пароль: Demo2026!')
    bullet(doc, 'Открыть проект «Демо-проект (все типы ресурсов)» — в нём ресурсы всех типов и все варианты расчёта.')
    bullet(doc, 'Финансовые показатели (взносы / наценка / НДС) и сводная таблица — на странице проекта.')
    bullet(doc, 'Документы КП и НМА (PDF/Excel/Word) — кнопка «Документы» на странице проекта.')

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    doc.save(OUT)
    print('Сохранено:', OUT)


if __name__ == '__main__':
    build()
